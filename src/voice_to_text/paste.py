"""Type text into the focused app by pasting it, then put the clipboard back."""

import time

import Quartz
from AppKit import NSPasteboard, NSPasteboardContentsCurrentHostOnly, NSPasteboardItem, NSPasteboardTypeString
from PyObjCTools import AppHelper

from .hotkey import SYNTHETIC_EVENT_TAG

_KEY_V = 9  # kVK_ANSI_V
_KEY_COMMAND = 55  # kVK_Command
_MODIFIERS = (
    Quartz.kCGEventFlagMaskCommand
    | Quartz.kCGEventFlagMaskShift
    | Quartz.kCGEventFlagMaskAlternate
    | Quartz.kCGEventFlagMaskControl
    | Quartz.kCGEventFlagMaskSecondaryFn
)
# Tells clipboard managers (Maccy, Raycast, ...) not to record our temporary text.
# https://nspasteboard.org
_IGNORE_MARKERS = ("org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType")


def paste_text(text: str, restore_after_s: float = 0.3) -> None:
    """Paste text into the focused app. Must run on the main thread."""
    pasteboard = NSPasteboard.generalPasteboard()
    saved = _snapshot(pasteboard)

    pasteboard.prepareForNewContentsWithOptions_(NSPasteboardContentsCurrentHostOnly)
    item = NSPasteboardItem.alloc().init()
    item.setString_forType_(text, NSPasteboardTypeString)
    for marker in _IGNORE_MARKERS:
        item.setString_forType_("", marker)
    pasteboard.writeObjects_([item])
    ours = pasteboard.changeCount()

    _wait_for_modifiers_released()
    _post_cmd_v()

    def restore() -> None:
        if pasteboard.changeCount() == ours:  # only if nothing new was copied meanwhile
            _restore(pasteboard, saved)

    # The target app reads the clipboard asynchronously, so restore a moment later.
    AppHelper.callLater(restore_after_s, restore)


def _snapshot(pasteboard) -> list[dict]:
    items = []
    for item in pasteboard.pasteboardItems() or []:
        types = {}
        for kind in item.types():
            data = item.dataForType_(kind)
            if data is not None:
                types[kind] = data
        items.append(types)
    return items


def _restore(pasteboard, items: list[dict]) -> None:
    pasteboard.clearContents()
    restored = []
    for types in items:
        item = NSPasteboardItem.alloc().init()
        for kind, data in types.items():
            item.setData_forType_(data, kind)
        restored.append(item)
    if restored:
        pasteboard.writeObjects_(restored)


def _wait_for_modifiers_released(timeout_s: float = 0.3) -> None:
    """A still-held Option or Shift would turn our Cmd+V into a different shortcut."""
    deadline = time.monotonic() + timeout_s
    while Quartz.CGEventSourceFlagsState(Quartz.kCGEventSourceStateHIDSystemState) & _MODIFIERS:
        if time.monotonic() > deadline:
            break
        time.sleep(0.01)


def _post_cmd_v() -> None:
    source = Quartz.CGEventSourceCreate(Quartz.kCGEventSourceStatePrivate)
    command = Quartz.kCGEventFlagMaskCommand
    for keycode, down, flags in (
        (_KEY_COMMAND, True, command),
        (_KEY_V, True, command),
        (_KEY_V, False, command),
        (_KEY_COMMAND, False, 0),
    ):
        event = Quartz.CGEventCreateKeyboardEvent(source, keycode, down)
        Quartz.CGEventSetFlags(event, flags)
        Quartz.CGEventSetIntegerValueField(event, Quartz.kCGEventSourceUserData, SYNTHETIC_EVENT_TAG)
        Quartz.CGEventPost(Quartz.kCGHIDEventTap, event)
